export function getModelForVariant(variantId) {
  return (
    ASSET_REGISTRY.models.find(
      (m) => m.variantId === variantId && m.status === 'validated'
    ) || null
  );
}

export function getRendersForProduct(productId, variantId = null) {
  return ASSET_REGISTRY.renders.filter(
    (r) =>
      r.productId === productId &&
      (!variantId || r.variantId === variantId) &&
      r.status === 'published'
  );
}
